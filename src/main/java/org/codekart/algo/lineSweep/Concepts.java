package org.codekart.algo.lineSweep;

public class Concepts {
    // Horizontal Line Sweep. - Y axis is the line of sweep
    // Vertical Line Sweep - X axis is the line of sweep

    /**
     * Events:
     * - Points where something changes. For example, in the case of intervals, the start and end points of the intervals are events.
     */

    /**
     * When to use Line Sweep Algorithm?
     * 1. When we have to find the number of intervals that overlap at any point
     * 2. Overlapping intervals
     * 3. Scheduling problems
     * 4. Geometric problems
     * 5. Area/ Skyline problems
     */
}
